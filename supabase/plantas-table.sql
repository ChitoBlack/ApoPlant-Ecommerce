create table if not exists public.plantas (
  id bigint generated by default as identity primary key,
  nombre text not null,
  precio bigint not null check (precio > 0),
  descripcion text not null,
  cuidado text not null,
  imagen text not null default '',
  categoria text not null check (categoria in ('interior', 'exterior')),
  luz text check (luz is null or luz in ('directa', 'indirecta', 'sombra')),
  riego text check (riego is null or riego in ('bajo', 'moderado', 'frecuente')),
  dificultad text check (dificultad is null or dificultad in ('facil', 'intermedia', 'avanzada')),
  apta_mascotas boolean,
  stock integer not null default 0 check (stock >= 0),
  created_at timestamptz not null default now()
);

alter table public.plantas enable row level security;

drop policy if exists "select_public_plantas" on public.plantas;
create policy "select_public_plantas" on public.plantas
  for select to anon, authenticated using (true);
